        <span class="tag">Sumo Revitalizante</span>
        <h2>1. Sumo Verde Especial de Espinafres e Gengibre</h2>
        <p>Uma excelente forma de começar o dia com energia e hidratação. Este sumo combina os benefícios antioxidantes dos vegetais verdes com o toque termogénico do gengibre.</p>
        
        <div class="ingredients">
            <h3>Ingredientes:</h3>
            <ul>
                <li>1 chávena de folhas de espinafres frescos</li>
                <li>1 maçã verde com casca, sem sementes</li>
                <li>1 pepino médio</li>
                <li>1 colher de café de gengibre fresco ralado</li>
                <li>Sumo de meio limão</li>
                <li>200ml de água de coco ou água filtrada</li>
            </ul>
        </div>
        
        <div class="method">
            <h3>Modo de Preparação:</h3>
            <ol>
                <li>Lave muito bem todos os ingredientes sob água corrente.</li>
                <li>Corte a maçã e o pepino em pedaços pequenos para facilitar a trituração.</li>
                <li>Coloque todos os ingredientes no liquidificador, adicionando a água de coco por último.</li>
                <li>Triture na velocidade máxima até obter uma mistura perfeitamente homogénea.</li>
                <li>Sirva de imediato (preferencialmente sem coar para aproveitar todas as fibras alimentares).</li>
            </ol>
        </div>
    </div>

    <div class="recipe-card">
        <span class="tag">Infusão Natural</span>
        <h2>2. Infusão de Alecrim e Hortelã para a Digestão</h2>
        <p>Esta infusão é perfeita para consumir após as refeições principais, ajudando na digestão e proporcionando uma sensação imediata de leveza.</p>
        
        <div class="ingredients">
            <h3>Ingredientes:</h3>
            <ul>
                <li>1 colher de sopa de folhas de alecrim fresco</li>
                <li>5 a 6 folhas de hortelã fresca</li>
                <li>500ml de água fervente</li>
                <li>1 rodela de limão (opcional)</li>
            </ul>
        </div>
        
        <div class="method">
            <h3>Modo de Preparação:</h3>
            <ol>
                <li>Aqueça a água até levantar fervura e desligue o lume.</li>
                <li>Adicione as folhas de alecrim e hortelã diretamente na água quente.</li>
                <li>Tape o recipiente e deixe repousar em infusão durante cerca de 7 a 10 minutos.</li>
                <li>Coe a infusão e sirva morna. Se desejar, adicione a rodela de limão para um sabor mais fresco.</li>
            </ol>
        </div>
    </div>
